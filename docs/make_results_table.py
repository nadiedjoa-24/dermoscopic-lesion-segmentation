"""Generate the LaTeX results tables of the report straight from the benchmark CSV.

Run from the repository root after `scripts/run_benchmark.py`::

    python docs/make_results_table.py

Writing the tables from the data rather than by hand is what keeps the report,
the README and the measurements from drifting apart.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "reports" / "per_image_results.csv"
OUTPUT = ROOT / "docs" / "results_tables.tex"

METHODS = {
    "Otsu": "Multi-channel Otsu",
    "LBP": "LBP Clustering",
    "SRM": "Statistical Region Merging",
}


def overall_table(frame: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r"Method & Dice (mask) & Dice (with convex hull) \\",
        r"\midrule",
    ]
    for key, label in METHODS.items():
        lines.append(f"{label} & {frame[key].mean():.3f} & {frame[key + '_Hull'].mean():.3f} " + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def category_table(frame: pd.DataFrame) -> str:
    melanoma = frame[frame.Category == "melanoma"]
    nevus = frame[frame.Category == "nevus"]
    lines = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"& \multicolumn{2}{c}{Melanoma} & \multicolumn{2}{c}{Nevus} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
        r"Method & mask & + hull & mask & + hull \\",
        r"\midrule",
    ]
    for key, label in METHODS.items():
        lines.append(
            f"{label} & {melanoma[key].mean():.3f} & {melanoma[key + '_Hull'].mean():.3f} "
            f"& {nevus[key].mean():.3f} & {nevus[key + '_Hull'].mean():.3f} " + r"\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def per_image_table(frame: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{llcccccc}",
        r"\toprule",
        r"Image & Class & Otsu & +hull & LBP & +hull & SRM & +hull \\",
        r"\midrule",
    ]
    for _, row in frame.iterrows():
        name = row["Image"].replace(".jpg", "").replace("_", r"\_")
        lines.append(
            f"{name} & {row['Category']} & "
            f"{row['Otsu']:.2f} & {row['Otsu_Hull']:.2f} & "
            f"{row['LBP']:.2f} & {row['LBP_Hull']:.2f} & "
            f"{row['SRM']:.2f} & {row['SRM_Hull']:.2f} " + r"\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def macros(frame: pd.DataFrame) -> str:
    """Single numbers quoted in the prose, as LaTeX macros."""
    definitions = []
    for key in METHODS:
        definitions.append(rf"\newcommand{{\dice{key}}}{{{frame[key].mean():.3f}}}")
        definitions.append(rf"\newcommand{{\dice{key}Hull}}{{{frame[key + '_Hull'].mean():.3f}}}")
    definitions.append(rf"\newcommand{{\nimages}}{{{len(frame)}}}")
    best = max(METHODS, key=lambda key: frame[key].mean())
    definitions.append(rf"\newcommand{{\bestmethod}}{{{METHODS[best]}}}")
    return "\n".join(definitions)


def main() -> None:
    frame = pd.read_csv(RESULTS)
    OUTPUT.write_text(
        "% Generated by docs/make_results_table.py -- do not edit by hand.\n"
        + macros(frame)
        + "\n\n\\newcommand{\\overalltable}{%\n"
        + overall_table(frame)
        + "\n}\n\n\\newcommand{\\categorytable}{%\n"
        + category_table(frame)
        + "\n}\n\n\\newcommand{\\perimagetable}{%\n"
        + per_image_table(frame)
        + "\n}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)} from {len(frame)} rows")


if __name__ == "__main__":
    main()
